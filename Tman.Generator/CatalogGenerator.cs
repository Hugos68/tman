        private static readonly string[] VariantExtensions = [".prefab.gbx", ".staticobject.gbx", ".vegettreemodel.gbx"];

        public static void Run(string paksDirectory, string outDirectory, string? projectRoot, string? customSubdirectory)
        {
            using var store = new PakStore(paksDirectory);
            Directory.CreateDirectory(outDirectory);
            var blocks = Blocks(store);
            var blocksPath = System.IO.Path.Combine(outDirectory, "Blocks.g.cs");
            File.WriteAllText(blocksPath, Emitter.Blocks(blocks, Families(blocks.ToDictionary(kv => kv.Key, kv => kv.Value.Waypoint, StringComparer.Ordinal), false)), new UTF8Encoding(false));
            Console.WriteLine($"wrote {blocksPath}: {blocks.Count} blocks");
            var items = Items(store);
            var itemsPath = System.IO.Path.Combine(outDirectory, "Items.g.cs");
            File.WriteAllText(itemsPath, Emitter.Items("Items", items.Values, Families(items.ToDictionary(kv => kv.Key, kv => kv.Value.Waypoint, StringComparer.Ordinal), true)), new UTF8Encoding(false));
            Console.WriteLine($"wrote {itemsPath}: {items.Count} items");
            if (projectRoot is not null && customSubdirectory is not null)
            {
                var custom = Custom(projectRoot, customSubdirectory);
                var customPath = System.IO.Path.Combine(outDirectory, "Custom.g.cs");
                File.WriteAllText(customPath, Emitter.Items("Custom", custom, []), new UTF8Encoding(false));
                Console.WriteLine($"wrote {customPath}: {custom.Count} items");
            }
        }

        private static readonly (int Kind, string Token)[] KindTokens = [(0, "Start"), (1, "Finish"), (2, "Checkpoint"), (4, "Multilap")];

        public static List<(string Name, int Kind, string Twin, bool HalfTurned)> Families(IReadOnlyDictionary<string, int?> waypoints, bool gates)
        {
            var families = new List<(string Name, int Kind, string Twin, bool HalfTurned)>();
            bool Is(string name, int kind) => waypoints.TryGetValue(name, out var w) && w == kind;
            foreach (var (name, waypoint) in waypoints.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            {
                if (waypoint is null || KindTokens.All(k => k.Kind != waypoint))
                {
                    continue;
                }
                var own = KindTokens.First(k => k.Kind == waypoint).Token;
                var at = name.IndexOf(own, StringComparison.Ordinal);
                var sideGate = gates ? System.Text.RegularExpressions.Regex.Match(name, "^Gate(Start|Checkpoint|Multilap)(Left|Right)([0-9]+)m$") : System.Text.RegularExpressions.Match.Empty;
                var finishGate = gates ? System.Text.RegularExpressions.Regex.Match(name, "^GateFinish([0-9]+)m$") : System.Text.RegularExpressions.Match.Empty;
                foreach (var (kind, token) in KindTokens)
                {
                    if (kind == waypoint)
                    {
                        continue;
                    }
                    var twin = at >= 0 ? name[..at] + token + name[(at + own.Length)..] : null;
                    var halfTurned = false;
                    if (twin is null || !Is(twin, kind))
                    {
                        twin = finishGate.Success ? $"Gate{token}Right{finishGate.Groups[1].Value}m" : sideGate.Success && kind == 1 ? $"GateFinish{sideGate.Groups[3].Value}m" : null;
                        halfTurned = sideGate.Success && kind == 1 && sideGate.Groups[2].Value == "Left";
                    }
                    if (twin is not null && Is(twin, kind))
                    {
                        families.Add((name, kind, twin, halfTurned));
                    }
                }
            }
            return families;
        }

        public static int? CollectionBit(string logical)
        {
            var top = logical.Split('\\')[0];
            for (var i = 0; i < PakStore.Paks.Count; i++)
            {
                if (string.Equals(PakStore.Paks[i].Name, top, StringComparison.OrdinalIgnoreCase))
                {
                    return 1 << i;
                }
            }
            return null;
        }

        public static SortedDictionary<string, BlockRow> Blocks(PakStore store)
        {
            var blocks = new SortedDictionary<string, BlockRow>(StringComparer.Ordinal);
            foreach (var logical in store.Entries)
            {
                var upper = logical.ToUpperInvariant();
                if (!upper.Contains("\\GAMECTNBLOCKINFO\\") || !upper.EndsWith(".GBX"))
                {
                    continue;
                }
                if (CollectionBit(logical) is not { } bit)
                {
                    continue;
                }
                if (store.Open(logical)?.Node is not CGameCtnBlockInfo info)
                {
                    continue;
                }
                var name = !string.IsNullOrEmpty(info.Ident.Id) ? info.Ident.Id : !string.IsNullOrEmpty(info.Name) ? info.Name : logical.Split('\\')[^1].Split('.')[0];
                if (name.Length == 0)
                {
                    continue;
                }
                var ground = Facts(info.VariantBaseGround);
                var air = Facts(info.VariantBaseAir);
                var (size, cells) = ground ?? air ?? ((1, 1), [(0, 0)]);
                var full = cells.Count >= size.Item1 * size.Item2;
                var variants = Has(info.VariantBaseGround) + Has(info.VariantBaseAir) + (info.AdditionalVariantsGround ?? []).Sum(Has) + (info.AdditionalVariantsAir ?? []).Sum(Has);
                int? waypoint = info.Chunks.Any(c => c.Id == 0x0304E026) ? (int)info.WayPointType : null;
                var row = new BlockRow(name, size.Item1, size.Item2, full ? null : cells, bit, waypoint, ground is not null, air is not null, variants);
                if (blocks.TryGetValue(name, out var existing))
                {
                    existing.Collections |= bit;
                    existing.Variants = Math.Max(existing.Variants, row.Variants);
                    existing.Ground |= row.Ground;
                    existing.Air |= row.Air;
                }
                else
                {
                    blocks.Add(name, row);
                }
            }
            return blocks;
        }

        private static int Has(CGameCtnBlockInfoVariant? variant) =>
            variant is not null && ((variant.BlockUnitModels?.Length ?? 0) > 0 || (variant.Mobils ?? []).Any(list => list is { Length: > 0 })) ? 1 : 0;

        private static ((int, int), List<(int X, int Z)>)? Facts(CGameCtnBlockInfoVariant? variant)
        {
            var units = variant?.BlockUnitModels;
            if (units is null || units.Length == 0)
            {
                return null;
            }
            var sx = units.Max(u => u.RelativeOffset.X + 1);
            var sz = units.Max(u => u.RelativeOffset.Z + 1);
            var cells = units.Select(u => (u.RelativeOffset.X, u.RelativeOffset.Z)).Distinct().OrderBy(c => c.X).ThenBy(c => c.Z).ToList();
            return ((sx, sz), cells);
        }

        public static SortedDictionary<string, ItemRow> Items(PakStore store)
        {
            var items = new SortedDictionary<string, ItemRow>(StringComparer.Ordinal);
            foreach (var logical in store.Entries)
            {
                var upper = logical.ToUpperInvariant();
                if (!upper.Contains("\\ITEMS\\") || !upper.EndsWith(".ITEM.GBX"))
                {
                    continue;
                }
                if (CollectionBit(logical) is not { } bit)
                {
                    continue;
                }
                var name = logical.Split('\\')[^1];
                name = name.EndsWith(".Item.Gbx") ? name[..^9] : name.EndsWith(".item.gbx") ? name[..^9] : name;
                var gbx = store.Open(logical);
                var externals = (gbx?.RefTable?.Files ?? []).Select(f => f.FilePath).Where(p => VariantExtensions.Any(p.ToLowerInvariant().EndsWith)).ToList();
                var waypoint = ItemWaypoint(store, logical, gbx);
                var size = new Vec3(0, 0, 0);
                if (externals.Count > 0)
                {
                    var picked = externals[0];
                    if (picked.EndsWith(".vegettreemodel.gbx", StringComparison.OrdinalIgnoreCase))
                    {
                        size = VegetationSizes.Sizes.GetValueOrDefault(name);
                    }
                    else
                    {
                        size = SizeWalk.Measure(store, PakStore.Logical(logical, gbx!.RefTable!.AncestorLevel, picked)) ?? size;
                    }
                }
                var row = new ItemRow(name, "Nadeo", null, bit, waypoint, externals.Count, size);
                if (items.TryGetValue(name, out var existing))
                {
                    existing.Collections |= bit;
                    existing.Variants = Math.Max(existing.Variants, row.Variants);
                }
                else
                {
                    items.Add(name, row);
                }
            }
            return items;
        }

        private static int? ItemWaypoint(PakStore store, string logical, Gbx? gbx)
        {
            if (gbx?.Node is CGameItemModel item)
            {
                return item.Chunks.Any(c => c.Id == 0x2E00201F) ? (int)item.WaypointType : null;
            }
            return FindWaypoint(store.ReadDecompressed(logical));
        }

        public static int? FindWaypoint(byte[]? bytes)
        {
            if (bytes is null)
            {
                return null;
            }
            var position = bytes.AsSpan().IndexOf(new byte[] { 0x1F, 0x20, 0x00, 0x2E });
            if (position < 0 || position + 12 > bytes.Length)
            {
                return null;
            }
            var version = BitConverter.ToUInt32(bytes, position + 4);
            var type = BitConverter.ToUInt32(bytes, position + 8);
            return version <= 20 && type <= 5 ? (int)type : null;
        }

        public static List<ItemRow> Custom(string projectRoot, string subdirectory)
        {
            var root = System.IO.Path.GetFullPath(projectRoot);
            var files = Directory.Exists(System.IO.Path.Combine(root, subdirectory))
                ? Directory.EnumerateFiles(System.IO.Path.Combine(root, subdirectory), "*.Item.Gbx", SearchOption.AllDirectories).Where(f => f.EndsWith(".Item.Gbx", StringComparison.Ordinal)).ToList()
                : [];
            files.Sort((a, b) => ComparePaths(System.IO.Path.GetRelativePath(root, a), System.IO.Path.GetRelativePath(root, b)));
            var rows = new List<ItemRow>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var path in files)
            {
                var file = System.IO.Path.GetFileName(path);
                if (!seen.Add(file))
                {
                    continue;
                }
                var relative = System.IO.Path.GetRelativePath(root, path).Replace('\\', '/');
                int? waypoint = null;
                var size = new Vec3(0, 0, 0);
                CGameItemModel? item = null;
                try
                {
                    item = Gbx.ParseNode<CGameItemModel>(path);
                }
                catch (Exception)
                {
                }
                if (item is not null)
                {
                    waypoint = item.Chunks.Any(c => c.Id == 0x2E00201F) ? (int)item.WaypointType : null;
                    size = CustomSize(item);
                }
                else
                {
                    waypoint = FindWaypoint(File.ReadAllBytes(path));
                }
                rows.Add(new ItemRow(file, file, relative, 31, waypoint, 1, size));
            }
            return rows;
        }

        private static int ComparePaths(string a, string b)
        {
            var pa = a.Split(System.IO.Path.DirectorySeparatorChar);
            var pb = b.Split(System.IO.Path.DirectorySeparatorChar);
            for (var i = 0; i < Math.Min(pa.Length, pb.Length); i++)
            {
                var c = string.CompareOrdinal(pa[i], pb[i]);
                if (c != 0)
                {
                    return c;
                }
            }
            return pa.Length.CompareTo(pb.Length);
        }

        private static Vec3 CustomSize(CGameItemModel item)
        {
            float lx = float.PositiveInfinity, ly = float.PositiveInfinity, lz = float.PositiveInfinity;
            float hx = float.NegativeInfinity, hy = float.NegativeInfinity, hz = float.NegativeInfinity;
            void Point(Vec3 p)
            {
                lx = MathF.Min(lx, p.X); ly = MathF.Min(ly, p.Y); lz = MathF.Min(lz, p.Z);
                hx = MathF.Max(hx, p.X); hy = MathF.Max(hy, p.Y); hz = MathF.Max(hz, p.Z);
            }
            void Box(float x, float y, float z, float x2, float y2, float z2)
            {
                Point(new Vec3(x, y, z));
                Point(new Vec3(x2, y2, z2));
            }
            void Surf(CPlugSurface? surface)
            {
                if (surface?.Surf is CPlugSurface.Mesh mesh && mesh.Vertices is { Length: > 0 })
                {
                    foreach (var v in mesh.Vertices)
                    {
                        Point(v);
                    }
                }
            }
            if (item.EntityModelEdition is CGameCommonItemEntityModelEdition edition && edition.MeshCrystal is { } crystal)
            {
                foreach (var layer in crystal.Layers)
                {
                    var positions = layer switch
                    {
                        CPlugCrystal.GeometryLayer g => g.Crystal?.Positions,
                        CPlugCrystal.TriggerLayer t => t.Crystal?.Positions,
                        _ => null,
                    };
                    foreach (var p in positions ?? [])
                    {
                        Point(p);
                    }
                }
            }
            else if (item.EntityModel is CGameCommonItemEntityModel entity)
            {
                foreach (var visual in entity.StaticObject?.Mesh?.Visuals ?? [])
                {
                    var b = visual.BoundingBox;
                    Box(b.X - b.X2, b.Y - b.Y2, b.Z - b.Z2, b.X + b.X2, b.Y + b.Y2, b.Z + b.Z2);
                }
                Surf(entity.StaticObject?.Shape);
                Surf(entity.TriggerShape as CPlugSurface);
            }
            return float.IsFinite(lx) ? new Vec3(hx - lx, hy - ly, hz - lz) : new Vec3(0, 0, 0);
        }
