using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Tman.Paks;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Tman.Generator
{
    internal static class Emitter
    {
        private const string Namespace = "Tman.Core.Catalog";

        private const string Header = "// generated by Tman.Generator from the game's pak files (Stadium, RedIsland, WhiteShore, GreenCoast, BlueBay); do not edit by hand";

        private const string ItemExtension = ".Item.Gbx";

        private const int AllCollections = 31;

        private const int SizeDecimals = 3;

        private const string LineEnding = "\r\n";

        private static readonly string[] Usings = ["System.Collections.Generic", "GBX.NET"];

        private static readonly (int Kind, string Name)[] Waypoints = [(0, "Start"), (1, "Finish"), (2, "Checkpoint"), (4, "StartFinish")];

        public static string Blocks(SortedDictionary<string, BlockRow> blocks, List<(string Name, int Kind, string Twin, bool HalfTurned)> families)
        {
            var identifiers = new Identifiers();
            var fields = blocks.Select(pair => Field("Block", identifiers.For(pair.Key), BlockCreation(pair.Key, pair.Value))).ToList();
            var byId = IdDictionary("Block", blocks.Keys.Select(id => (id, identifiers.Of(id))));
            var plainOf = ReadOnlyDictionary("PlainOf", "string", "Block", PlainTwins(blocks, identifiers).Select(pair => (Key: (ExpressionSyntax)Literal(pair.Checkpoint), Value: Name(pair.PlainIdentifier))));
            var members = fields.Concat([byId, FromId("Block", "block"), plainOf, FamiliesDictionary("Block", families, identifiers)]);
            return Unit("Blocks", members);
        }

        public static string Items(string className, IEnumerable<ItemRow> items, List<(string Name, int Kind, string Twin, bool HalfTurned)> families)
        {
            var identifiers = new Identifiers();
            var rows = items.ToList();
            var fields = rows.Select(item => Field("Item", identifiers.For(item.Id, className == "Items" ? item.Id : item.Id[..^ItemExtension.Length]), ItemCreation(item))).ToList();
            var members = fields.Concat([IdDictionary("Item", rows.Select(item => (item.Id, identifiers.Of(item.Id)))), FromId("Item", "item")]);
            if (className == "Items")
            {
                members = members.Concat([FamiliesDictionary("Item", families, identifiers), HalfTurnedSet(families)]);
            }
            return Unit(className, members);
        }

        private static string Unit(string className, IEnumerable<MemberDeclarationSyntax> members)
        {
            var type = ClassDeclaration(className)
                .WithModifiers(TokenList(Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword)))
                .WithMembers(List(members));
            var unit = CompilationUnit()
                .WithUsings(List(Usings.Select(name => UsingDirective(ParseName(name)))))
                .WithMembers(SingletonList<MemberDeclarationSyntax>(NamespaceDeclaration(ParseName(Namespace)).WithMembers(SingletonList<MemberDeclarationSyntax>(type))))
                .NormalizeWhitespace(eol: LineEnding)
                .WithLeadingTrivia(Comment(Header), EndOfLine(LineEnding));
            return unit.ToFullString();
        }

        private static FieldDeclarationSyntax Field(string type, string identifier, ExpressionSyntax value) =>
            FieldDeclaration(VariableDeclaration(IdentifierName(type)).WithVariables(SingletonSeparatedList(VariableDeclarator(identifier).WithInitializer(EqualsValueClause(value)))))
                .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword), Token(SyntaxKind.ReadOnlyKeyword)));

        private static ExpressionSyntax BlockCreation(string id, BlockRow block) =>
            ImplicitObjectCreationExpression().WithArgumentList(Arguments(
                Literal(id),
                Literal(block.SizeX),
                Literal(block.SizeZ),
                Cells(block.Cells),
                Collections(block.Collections),
                Waypoint(block.Waypoint),
                Literal(block.Ground),
                Literal(block.Air),
                Literal(block.Variants)));

        private static ExpressionSyntax ItemCreation(ItemRow item) =>
            ImplicitObjectCreationExpression().WithArgumentList(Arguments(
                Literal(item.Id),
                Literal(item.Author),
                item.Path is null ? Null() : Literal(item.Path),
                Collections(item.Collections),
                Waypoint(item.Waypoint),
                Literal(item.Variants),
                ObjectCreationExpression(IdentifierName("Vec3")).WithArgumentList(Arguments(Literal(item.Size.X), Literal(item.Size.Y), Literal(item.Size.Z)))));

        private static ExpressionSyntax Cells(List<(int X, int Z)>? cells) => cells is null
            ? Null()
            : CollectionExpression(SeparatedList<CollectionElementSyntax>(cells.Select(cell => ExpressionElement(CollectionExpression(SeparatedList<CollectionElementSyntax>([ExpressionElement(Literal(cell.X)), ExpressionElement(Literal(cell.Z))]))))));

        private static ExpressionSyntax Collections(int mask)
        {
            if (mask == AllCollections)
            {
                return Member("Collections", "All");
            }
            var flags = PakStore.Paks.Select((pak, index) => (pak.Name, Bit: 1 << index)).Where(pak => (mask & pak.Bit) != 0).Select(pak => (ExpressionSyntax)Member("Collections", pak.Name)).ToList();
            return flags.Count == 0 ? Literal(0) : flags.Skip(1).Aggregate(flags[0], (left, right) => BinaryExpression(SyntaxKind.BitwiseOrExpression, left, right));
        }

        private static ExpressionSyntax Waypoint(int? kind) => Member("Waypoint", Waypoints.FirstOrDefault(waypoint => waypoint.Kind == kind).Name ?? "None");

        private static MemberDeclarationSyntax IdDictionary(string type, IEnumerable<(string Id, string Identifier)> entries) =>
            ReadOnlyDictionary("ById", "string", type, entries.Select(entry => (Key: (ExpressionSyntax)Literal(entry.Id), Value: Name(entry.Identifier))));

        private static MemberDeclarationSyntax FamiliesDictionary(string type, List<(string Name, int Kind, string Twin, bool HalfTurned)> families, Identifiers identifiers) =>
            ReadOnlyDictionary("Families", "(string, Waypoint)", type, families.Select(family => (Key: Tuple(family.Name, family.Kind), Value: Name(identifiers.Of(family.Twin)))));

        private static MemberDeclarationSyntax HalfTurnedSet(List<(string Name, int Kind, string Twin, bool HalfTurned)> families)
        {
            var elementType = ParseTypeName("(string, Waypoint)");
            var creation = ObjectCreationExpression(GenericName("HashSet").WithTypeArgumentList(TypeArgumentList(SingletonSeparatedList(elementType))))
                .WithInitializer(InitializerExpression(SyntaxKind.CollectionInitializerExpression, SeparatedList(families.Where(family => family.HalfTurned).Select(family => Tuple(family.Name, family.Kind)))));
            return Field(ParseTypeName("IReadOnlySet<(string, Waypoint)>"), "HalfTurned", creation);
        }

        private static MemberDeclarationSyntax ReadOnlyDictionary(string name, string keyType, string valueType, IEnumerable<(ExpressionSyntax Key, ExpressionSyntax Value)> entries)
        {
            var creation = ObjectCreationExpression(ParseTypeName($"Dictionary<{keyType}, {valueType}>"))
                .WithInitializer(InitializerExpression(SyntaxKind.ObjectInitializerExpression, SeparatedList<ExpressionSyntax>(entries.Select(entry =>
                    AssignmentExpression(SyntaxKind.SimpleAssignmentExpression, ImplicitElementAccess().WithArgumentList(BracketedArgumentList(SingletonSeparatedList(Argument(entry.Key)))), entry.Value)))));
            return Field(ParseTypeName($"IReadOnlyDictionary<{keyType}, {valueType}>"), name, creation);
        }

        private static FieldDeclarationSyntax Field(TypeSyntax type, string identifier, ExpressionSyntax value) =>
            FieldDeclaration(VariableDeclaration(type).WithVariables(SingletonSeparatedList(VariableDeclarator(identifier).WithInitializer(EqualsValueClause(value)))))
                .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword), Token(SyntaxKind.ReadOnlyKeyword)));

        private static MemberDeclarationSyntax FromId(string type, string variable) =>
            MethodDeclaration(NullableType(IdentifierName(type)), "FromId")
                .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword)))
                .WithParameterList(ParameterList(SingletonSeparatedList(Parameter(Identifier("id")).WithType(PredefinedType(Token(SyntaxKind.StringKeyword))))))
                .WithExpressionBody(ArrowExpressionClause(ParseExpression($"ById.TryGetValue(id, out var {variable}) ? {variable} : null")))
                .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        private static IEnumerable<(string Checkpoint, string PlainIdentifier)> PlainTwins(SortedDictionary<string, BlockRow> blocks, Identifiers identifiers) =>
            CheckpointTwins.Twins
                .Where(pair => blocks.ContainsKey(pair.Checkpoint) && blocks.ContainsKey(pair.Plain))
                .OrderBy(pair => pair.Checkpoint, StringComparer.Ordinal)
                .Select(pair => (pair.Checkpoint, identifiers.Of(pair.Plain)));

        private static ExpressionSyntax Tuple(string name, int kind) =>
            TupleExpression(SeparatedList([Argument(Literal(name)), Argument(Waypoint(kind))]));

        private static ArgumentListSyntax Arguments(params ExpressionSyntax[] expressions) => ArgumentList(SeparatedList(expressions.Select(Argument)));

        private static ExpressionSyntax Member(string type, string member) => MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, IdentifierName(type), IdentifierName(member));

        private static ExpressionSyntax Name(string identifier) => IdentifierName(identifier);

        private static ExpressionSyntax Null() => LiteralExpression(SyntaxKind.NullLiteralExpression);

        private static ExpressionSyntax Literal(string value) => LiteralExpression(SyntaxKind.StringLiteralExpression, SyntaxFactory.Literal(value));

        private static ExpressionSyntax Literal(int value) => LiteralExpression(SyntaxKind.NumericLiteralExpression, SyntaxFactory.Literal(value));

        private static ExpressionSyntax Literal(bool value) => LiteralExpression(value ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression);

        private static ExpressionSyntax Literal(float value)
        {
            var rounded = (float)Math.Round(value, SizeDecimals, MidpointRounding.AwayFromZero);
            return LiteralExpression(SyntaxKind.NumericLiteralExpression, SyntaxFactory.Literal(rounded.ToString($"F{SizeDecimals}", CultureInfo.InvariantCulture) + "f", rounded));
        }
    }
}
